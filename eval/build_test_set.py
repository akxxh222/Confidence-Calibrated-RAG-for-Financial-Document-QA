def answerable(number, question, company, period, answer, evidence_key):
    return {
        "question_id": f"ans_{number:03d}",
        "question_text": question,
        "category": "answerable",
        "company": company,
        "doc_type": "10-K",
        "fiscal_period": period,
        "ground_truth_answer": answer,
        "evidence": [EVIDENCE[evidence_key]],
        "absence_check": None,
        "review": dict(REVIEW),
    }


