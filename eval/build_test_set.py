def write_jsonl(path, rows):
    path.write_text(
        "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows),
        encoding="utf-8",
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--force",
        action="store_true",
        help="replace existing JSONL files (this can erase review edits)",
    )
    args = parser.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    outputs = {
        OUT_DIR / "answerable.jsonl": ANSWERABLE,
        OUT_DIR / "false_premise.jsonl": FALSE_PREMISE,
        OUT_DIR / "unanswerable.jsonl": UNANSWERABLE,
    }
    existing = [path for path in outputs if path.exists()]
    if existing and not args.force:
        names = ", ".join(path.name for path in existing)
        raise FileExistsError(
            f"Refusing to overwrite reviewed files: {names}. "
            "Use --force only to rebuild the initial seed."
        )
    for path, rows in outputs.items():
        write_jsonl(path, rows)
    print(
        f"Wrote {len(ANSWERABLE)} answerable, {len(FALSE_PREMISE)} false-premise, "
        f"and {len(UNANSWERABLE)} unanswerable questions."
    )


if __name__ == "__main__":
    main()
